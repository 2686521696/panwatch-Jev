def main() -> None:
    init_db()
    db = SessionLocal()
    try:
        for name, stocks in GROUPS:
            group = db.query(StockGroup).filter(StockGroup.name == name).first()
            if group is None:
                created = create_stock_group(name, db)
                group_id = created["id"]
            else:
                group_id = group.id
            for symbol, stock_name in stocks:
                add_stock_to_group(group_id, symbol, stock_name, "CN", db)
            print(f"{name}: {len(stocks)}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
